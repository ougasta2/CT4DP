"""Rebuild the 2024 afternoon comparison from Ridge predictions and frozen regimes."""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("predictions", type=Path)
    parser.add_argument("regimes", type=Path)
    args = parser.parse_args()
    frame = pd.read_csv(args.predictions)
    local = pd.DatetimeIndex(pd.to_datetime(frame["HourUTC"], utc=True)).tz_convert("Europe/Copenhagen")
    expected = pd.date_range("2023-01-01", "2025-01-01", inclusive="left", freq="h", tz=local.tz)
    if not local.equals(expected) or not np.isfinite(frame[["prediction", "actual"]]).all().all():
        raise ValueError("Need finite, aligned Ridge predictions for every hour of 2023--2024.")
    frame["day"] = local.tz_localize(None).normalize()
    frame["error"] = (frame["prediction"] - frame["actual"]).abs()
    threshold = frame.loc[local.year == 2023, "error"].quantile(.90)
    frame["event"] = frame["error"] > threshold
    afternoon = frame.loc[(local.year == 2024) & (local.hour >= 12) & (local.hour < 18)]
    regimes = pd.read_csv(args.regimes, parse_dates=["day"], usecols=["day", "cluster"])
    daily = afternoon.groupby("day")["event"].agg(events="sum", hours="size")
    daily = daily.join(regimes.set_index("day"), validate="one_to_one")
    if len(daily) != 366 or not daily["hours"].eq(6).all() or daily["cluster"].isna().any():
        raise ValueError("Need 366 labelled delivery days and six afternoon hours per day.")

    cluster = daily["cluster"].eq(0)
    groups = [("All afternoons", daily), ("Cluster 0", daily[cluster]), ("Other clusters", daily[~cluster])]
    n = len(daily)
    rng = np.random.default_rng(42)
    blocks = rng.integers(0, n - 7 + 1, size=(5000, (n + 6) // 7))
    draws = (blocks[..., None] + np.arange(7)).reshape(5000, -1)[:, :n]
    c = cluster.to_numpy()[draws]
    e = daily["events"].to_numpy()[draws]
    h = daily["hours"].to_numpy()[draws]
    n0, n_other = (h * c).sum(axis=1), (h * ~c).sum(axis=1)
    valid = (n0 > 0) & (n_other > 0)
    diff = (e * c).sum(axis=1)[valid] / n0[valid] - (e * ~c).sum(axis=1)[valid] / n_other[valid]
    lo, hi = np.quantile(100 * diff, [.025, .975])
    print(f"2023 threshold {threshold:.8f}; 7-day block 95% interval [{lo:.2f}, {hi:.2f}] pp "
          f"({valid.sum()} draws)")

    rows = []
    rates = []
    for label, group in groups:
        events, hours = int(group["events"].sum()), int(group["hours"].sum())
        rate = 100 * events / hours
        rates.append(rate)
        print(f"{label}: {events}/{hours}, {rate:.4f}%")
        # Bars share a zero origin and use 5 pt per percentage point.
        rows.append(rf"{label} & \rule{{{5 * rate:.2f}pt}}{{5pt}} & {rate:.2f}\% ({events}/{hours}) \\")
    print(f"Cluster 0 minus other clusters: {rates[1] - rates[2]:+.2f} pp")
    figure = Path(__file__).with_name("afternoon_comparison.tex")
    figures = [r"% Generated by build_afternoon_comparison.py from the frozen Ridge predictions.",
               r"\begin{figure}[!t]", r"\centering", r"\small",
               r"\begin{tabular}{@{}llr@{}}", *rows, r"\end{tabular}",
               r"\caption{Large-error rates in 2024 for Copenhagen hours 12:00--17:59.",
               r"Bars start at zero and share a linear scale. Labels give events over hours.}",
               r"\label{fig:afternoon}", r"\end{figure}"]
    figure.write_text("\n".join(figures) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
